# Build the pinned V8 as a static monolith and install it for the host build.
#
# Why: spec §4.1 and §9 M1 replace QuickJS with V8 built from source (v0.2
# §11.2 option A). One script with one pin keeps dev-laptop builds and the CI
# tarball identical. See docs/build-v8.md for the pin, every GN arg and the cost.
#
# Usage: build_v8.sh [--print-args] [--help]
#   --print-args  print the GN args for this host and exit; fetches nothing and
#                 writes nothing.
# Environment:
#   SMZ_DEPS_DIR  dependency cache (default ~/.cache/smzuggler-dev/deps). All
#                 writes, including depot_tools' own caches, stay inside it.
#   SMZ_JOBS      ninja parallelism (default: ninja's own choice).
# Result: $SMZ_DEPS_DIR/v8/<version>/{include/,lib/libv8_monolith.a,
#         share/icudtl.dat,args.gn,v8-config.cmake}.
set -euo pipefail

# The V8 pin (spec §11 Q9, DEC-M1-T001). Changing it needs owner approval.
V8_VERSION=13.6.233.8
DEPOT_TOOLS_URL=https://chromium.googlesource.com/chromium/tools/depot_tools.git
V8_URL=https://chromium.googlesource.com/v8/v8.git

die() { echo "build_v8: $*" >&2; exit 1; }

# Map this machine to GN's target_cpu; only the 64-bit targets of spec §3 exist.
host_cpu() {
    case "$(uname -m)" in
        x86_64|amd64) echo x64 ;;
        aarch64|arm64) echo arm64 ;;
        *) die "unsupported CPU '$(uname -m)'; spec §3 targets x64 and arm64" ;;
    esac
}

# Print args.gn for this host. The "why" of each line is in docs/build-v8.md.
gn_args() {
    cat <<EOF
# smzuggler V8 pin: $V8_VERSION
is_debug = false
target_cpu = "$(host_cpu)"
v8_monolithic = true
is_component_build = false
use_custom_libcxx = false
v8_use_external_startup_data = false
v8_enable_i18n_support = true
icu_use_data_file = true
v8_enable_pointer_compression = true
v8_enable_sandbox = false
v8_enable_webassembly = true
symbol_level = 0
treat_warnings_as_errors = false
EOF
}

# Clone depot_tools once and keep every tool cache inside the deps dir.
setup_depot_tools() {
    local deps=$1 tools=$1/depot_tools
    if [ ! -d "$tools/.git" ]; then
        git clone --depth 1 "$DEPOT_TOOLS_URL" "$tools"
    fi
    export PATH="$tools:$PATH"
    export DEPOT_TOOLS_UPDATE=0 DEPOT_TOOLS_METRICS=0
    export XDG_CACHE_HOME="$deps/v8-cache" CIPD_CACHE_DIR="$deps/v8-cache/cipd"
    export VPYTHON_VIRTUALENV_ROOT="$deps/v8-cache/vpython"
    mkdir -p "$CIPD_CACHE_DIR" "$VPYTHON_VIRTUALENV_ROOT"
    # A fresh clone has no bundled python3 or CIPD tools until its one-time
    # bootstrap runs; with self-update off nothing else runs it, and gclient's
    # hooks then fail (python3_bin_reldir.txt missing). It is idempotent.
    (cd "$tools" && ./ensure_bootstrap) \
        || die "depot_tools bootstrap (ensure_bootstrap) failed in $tools"
}

# Check out exactly the pinned tag (and the DEPS it names) into v8-src/v8.
fetch_v8() {
    local src=$1/v8-src
    mkdir -p "$src"
    cat > "$src/.gclient" <<EOF
solutions = [{
  "name": "v8",
  "url": "$V8_URL@refs/tags/$V8_VERSION",
  "deps_file": "DEPS",
  "managed": False,
  "custom_deps": {},
}]
EOF
    (cd "$src" && gclient sync --no-history --force --reset -D) \
        || die "gclient sync of V8 $V8_VERSION failed; is the tag correct?"
    local got
    got=$(grep -E '^#define V8_(MAJOR|MINOR|BUILD|PATCH)_' \
          "$src/v8/include/v8-version.h" | awk '{print $3}' | paste -sd.)
    [ "$got" = "$V8_VERSION" ] || die "checked out V8 $got, pin is $V8_VERSION"
}

# Generate the build directory from gn_args and build only the monolith.
build_v8() {
    local v8=$1/v8-src/v8 out=$2
    mkdir -p "$out"
    gn_args > "$out/args.gn"
    (cd "$v8" && gn gen "$out") || die "gn gen failed in $out"
    local jobs=()
    if [ -n "${SMZ_JOBS:-}" ]; then jobs=(-j "$SMZ_JOBS"); fi
    (cd "$v8" && autoninja ${jobs[@]+"${jobs[@]}"} -C "$out" v8_monolith) \
        || die "ninja v8_monolith failed in $out"
}

# Write the CMake manifest. The defines must match the GN args: headers
# compiled without them disagree with the library on object layout.
write_cmake_config() {
    local prefix=$1
    cat > "$prefix/v8-config.cmake" <<'EOF'
# Generated by tools/v8/build_v8.sh; see docs/build-v8.md.
# SPDX-License-Identifier: GPL-3.0-or-later
# Copyright (C) 2026 The smzuggler contributors
get_filename_component(_smz_v8_prefix "${CMAKE_CURRENT_LIST_FILE}" DIRECTORY)
EOF
    cat >> "$prefix/v8-config.cmake" <<EOF
set(V8_VERSION "$V8_VERSION")
set(V8_ICU_DATA "\${_smz_v8_prefix}/share/icudtl.dat")
if(NOT TARGET V8::v8_monolith)
  find_package(Threads REQUIRED)
  add_library(V8::v8_monolith STATIC IMPORTED)
  set_target_properties(V8::v8_monolith PROPERTIES
    IMPORTED_LOCATION "\${_smz_v8_prefix}/lib/libv8_monolith.a"
    INTERFACE_INCLUDE_DIRECTORIES "\${_smz_v8_prefix}/include"
    INTERFACE_COMPILE_DEFINITIONS "V8_COMPRESS_POINTERS;V8_31BIT_SMIS_ON_64BIT_ARCH"
    INTERFACE_LINK_LIBRARIES "Threads::Threads;\${CMAKE_DL_LIBS}")
endif()
EOF
}

# Stage the install next to its final place, then swap it in, so an
# interrupted run never leaves a half-installed version behind.
install_v8() {
    local deps=$1 out=$2 v8=$1/v8-src/v8
    local prefix=$deps/v8/$V8_VERSION stage=$deps/v8/.$V8_VERSION.tmp
    rm -rf "$stage"
    mkdir -p "$stage/lib" "$stage/share"
    cp -R "$v8/include" "$stage/include"
    cp "$out/obj/libv8_monolith.a" "$stage/lib/"
    # The little-endian ICU data that GN would copy next to a binary.
    cp "$v8/third_party/icu/common/icudtl.dat" "$stage/share/"
    cp "$out/args.gn" "$stage/args.gn"
    git -C "$deps/depot_tools" rev-parse HEAD > "$stage/depot_tools.rev"
    write_cmake_config "$stage"
    rm -rf "$prefix"
    mv "$stage" "$prefix"
    echo "build_v8: installed V8 $V8_VERSION into $prefix"
}

main() {
    case "${1:-}" in
        --print-args) [ $# -eq 1 ] || die "--print-args takes no operands"
                      gn_args; return ;;
        -h|--help) sed -n '5,19p' "$0"; return ;;
        '') ;;
        *) die "unknown option '$1' (try --help)" ;;
    esac
    local deps=${SMZ_DEPS_DIR:-$HOME/.cache/smzuggler-dev/deps}
    mkdir -p "$deps"
    deps=$(cd "$deps" && pwd)
    setup_depot_tools "$deps"
    fetch_v8 "$deps"
    local out=$deps/v8-src/v8/out/smz-$V8_VERSION-$(host_cpu)
    build_v8 "$deps" "$out"
    install_v8 "$deps" "$out"
}

main "$@"
